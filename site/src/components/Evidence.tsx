// The recorded request, SQL and rows of one question. Shared by the caller
// example and every question page, so all 22 outcomes get the same inspection.

import { useState } from "react";
import type { Assessment, OutputContract, Request, ReviewFinding, Row, Score } from "../data/types";
import { Captured, ProseStatus, RowsTable, TableStatus } from "./parts";
import { readableSql } from "../app/sql";
import { matchRows, missingReference, parseReference, referenceAsRows } from "../app/compare";

export function RequestBlock({ request, contract }: { request: Request; contract: OutputContract }) {
  const [first, ...rest] = request.question.split("\n\n");
  return (
    <div className="request">
      <p className="request__label">The question as submitted</p>
      <blockquote className="request__q">{first}</blockquote>
      <details className="fold">
        <summary>Show the full submitted text ({rest.length} further paragraphs of output instructions)</summary>
        <Captured text={request.question} label="Complete submitted question text" />
      </details>
      <div className="request__grid">
        <div>
          <p className="request__label">Hint supplied with the question</p>
          <Captured text={request.evidence || "(none)"} label="Hint supplied with the question" />
        </div>
        <div>
          <p className="request__label">Required output columns</p>
          <ul className="fields">
            {contract.fields.map((f) => (
              <li key={f.name}>
                <code>{f.name}</code> <span className="muted">{f.type}</span>
              </li>
            ))}
          </ul>
          <p className="small muted">{contract.ordered ? "Row order is part of the answer." : "Row order is not part of the answer."}</p>
        </div>
      </div>
    </div>
  );
}

export function SqlPair({ sql, reference }: { sql: string; reference: string }) {
  const [asCaptured, setAsCaptured] = useState(false);
  const singleLine = !sql.includes("\n");
  return (
    <div className="sqlpair">
      <div className="sqlpair__col">
        <div className="sqlpair__head">
          <h3 className="sqlpair__title">SQL generated by Auto Ontology</h3>
          {singleLine ? (
            <button type="button" className="btn-quiet" aria-pressed={asCaptured} onClick={() => setAsCaptured(!asCaptured)}>
              {asCaptured ? "Add line breaks" : "Show as captured, on one line"}
            </button>
          ) : null}
        </div>
        <Captured className="sql" text={asCaptured ? sql : readableSql(sql)} label="Generated SQL" />
        {singleLine && !asCaptured ? <p className="small muted">The capture is one line. Line breaks were added before each clause; no other character changed.</p> : null}
      </div>
      <div className="sqlpair__col">
        <div className="sqlpair__head">
          <h3 className="sqlpair__title">Reference SQL used for scoring</h3>
        </div>
        <Captured className="sql" text={reference} label="Reference SQL" />
        <p className="small muted">Written with the question to produce the expected rows. It was not part of the submitted request.</p>
      </div>
    </div>
  );
}

export function Results({
  tables,
  referenceText,
  contract,
  score,
}: {
  tables: Row[][];
  referenceText: string;
  contract: OutputContract;
  score: Score;
}) {
  const fields = contract.fields.map((f) => f.name);
  const reference = parseReference(referenceText);
  const rows = tables[0] ?? [];
  const keys = rows.length ? Object.keys(rows[0]) : [];
  const columns = [...fields.filter((f) => keys.includes(f) || !rows.length), ...keys.filter((k) => !fields.includes(k))];
  const matched = reference ? matchRows(rows, reference, fields) : null;
  const missing = reference ? missingReference(rows, reference, fields) : [];
  const [showRaw, setShowRaw] = useState(false);
  return (
    <div className="results">
      <RowsTable
        rows={rows}
        columns={columns}
        caption={`Rows Auto Ontology returned (${rows.length}, in recorded order)`}
        rowNote={matched && !score.strict_rows_pass ? (_row, i) => (matched[i] ? "Also in the reference" : <strong className="fail-ink">Not in the reference</strong>) : undefined}
      />
      {tables.length > 1 ? <p className="small muted">This answer returned {tables.length} result tables; the first is shown.</p> : null}
      {reference ? (
        <RowsTable rows={referenceAsRows(reference, fields)} columns={fields} caption={`Reference rows (${reference.length})`} />
      ) : (
        <p className="small">The reference rows could not be read as a table; they are shown as captured below.</p>
      )}
      {score.strict_rows_pass ? <p className="small">Every returned row is in the reference, and nothing is missing.</p> : null}
      {missing.length > 0 ? <p className="small fail-ink">{missing.length} reference {missing.length === 1 ? "row was" : "rows were"} not returned.</p> : null}
      <button type="button" className="btn-quiet" aria-expanded={showRaw} onClick={() => setShowRaw(!showRaw)}>
        {showRaw ? "Hide" : "Show"} the reference rows as captured (JSON text)
      </button>
      {showRaw ? <Captured text={referenceText} label="Reference rows as captured" /> : null}
    </div>
  );
}

export function AssessmentBlock({ assessment, score, finding }: { assessment: Assessment; score: Score; finding: ReviewFinding | null }) {
  return (
    <div className="assess">
      <div className="assess__item">
        <p className="assess__head">
          Table check <TableStatus value={assessment.table_match} />
        </p>
        <p className="small">
          A program compared the returned rows with the reference rows: {score.agent_rows} returned, {score.reference_rows} expected;{" "}
          {score.values_match ? "values matched" : "values differed"}
          {score.order_matches ? "" : ", order differed"}.
        </p>
      </div>
      <div className="assess__item">
        <p className="assess__head">
          Prose review <ProseStatus value={assessment.prose_review} />
        </p>
        <p className="small">
          The author read the written answer{assessment.review_method === "author_review_not_blinded" ? " (not a blinded review)" : ""}
          {assessment.review_basis === "documented_aggregate" ? "; recorded as part of the run’s overall count." : "; recorded as an individual finding."}
        </p>
      </div>
      {finding ? (
        <div className="assess__finding">
          <p className="assess__head">The author’s finding</p>
          <p>
            <strong>Rows:</strong> {finding.reason}
          </p>
          <p>
            <strong>Prose:</strong> {finding.prose}
          </p>
        </div>
      ) : null}
    </div>
  );
}

export function AnswerProse({ text }: { text: string }) {
  return (
    <figure className="prose-answer">
      <figcaption>Auto Ontology’s written answer, verbatim</figcaption>
      <blockquote>{text}</blockquote>
    </figure>
  );
}
