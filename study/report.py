"""Write study/RESULTS.md from study/results/summary.json (corrected evaluator) and
study/results/frozen/summary.json (the references as frozen before the runs).

Run study/summarise.py --evaluator corrected first.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
S = json.loads((ROOT / "study/results/summary.json").read_text())
F = json.loads((ROOT / "study/results/frozen/summary.json").read_text())
power = json.loads((ROOT / "study/results/suite_power.json").read_text())
corrections = json.loads((ROOT / "study/questions/corrections.json").read_text())
cells = {(c["model"], c["arm"]): c for c in S["cells"]}
frozen = {(c["model"], c["arm"]): c for c in F["cells"]}
NAMES = {"deepseek": "DeepSeek v4.1 Flash", "nemotron": "Nemotron 3.5 Lightning"}
ARMS = [
    ("A", "Table names only (schema)"),
    ("B", "+ table descriptions (base model: descriptions, keys, joins)"),
    ("V", "+ ready-made queries without descriptions (views only)"),
    ("S", "+ table descriptions and ready-made queries (semantics layer)"),
]
C_ARMS = [
    ("C-native", "Code database, nothing imported"),
    ("C-base", "+ table descriptions"),
    ("C-semantics", "+ table descriptions and ready-made queries"),
]
models = [m for m in ("deepseek", "nemotron") if any(k[0] == m for k in cells)]


def fmt(c, key):
    if not c:
        return "—"
    vals = c[key]
    return f"{sum(vals) / len(vals):.1f} ({min(vals)}–{max(vals)})"


def mean(c, key):
    return f"{c[key + '_mean']:.1f}" if c else "—"


out = ["# Results", "",
       "Generated by `study/report.py` from `study/results/summary.json`. Protocol: [PROTOCOL.md](PROTOCOL.md). "
       "Questions: [questions/questions.json](questions/questions.json). Every response: `study/runs/`.", "",
       "**Snapshot** = exactly the reference rows on the repository's database. **Suite** (called *robust* elsewhere) = the "
       "same query also returns the reference rows on all eight counterfactual copies of that database, which catches many "
       "queries that are right on one database by coincidence. Each cell is the mean over repetitions, with the lowest and "
       "highest in brackets.", "",
       f"**Evaluator.** These scores use the corrected references ([corrections](questions/corrections.json), "
       f"[protocol](PROTOCOL.md#corrections-after-the-runs)): {len(corrections['corrections'])} reference queries that missed "
       f"a restriction stated in their question were corrected after the runs, and {len(corrections['accepted_readings'])} "
       "questions accept either of two readings. Snapshot scores are identical under both versions. The scores under the "
       "frozen references, as first published, are in [results/frozen/](results/frozen/RESULTS.md) and compared below.", ""]

out += ["## Direct prompting: 48 questions, four repositories, five repetitions", "",
        "Temperature 0, reasoning off, at most 4,000 output tokens, set in every request.", "",
        "| Model is given | " + " | ".join(f"{NAMES[m]} snapshot | {NAMES[m]} suite" for m in models) + " |",
        "| --- |" + " ---: | ---: |" * len(models)]
for arm, label in ARMS:
    out.append(f"| {arm}. {label} | " + " | ".join(f"{fmt(cells.get((m, arm)), 'snapshot')} | {fmt(cells.get((m, arm)), 'suite')}" for m in models) + " |")
out.append("")

if any(k[1].startswith("C") for k in cells):
    out += ["## Inside NVIDIA Auto Ontology: the 12 Auto Ontology questions, same agent, three runs each", "",
            "Every row queries the same code database written by the bridge. The agent, its retrieval, validation and repair, the "
            "requests and the chat model are fixed. "
            "C-base imports the base model; C-semantics adds the six layer views to the database and imports the model "
            "that describes them. Chat runs through Auto Ontology's own clients: temperature 0, its own output limits and "
            "the provider's default reasoning.", "",
            "| Auto Ontology is given | " + " | ".join(f"{NAMES[m]} snapshot | {NAMES[m]} suite" for m in models) + " |",
            "| --- |" + " ---: | ---: |" * len(models)]
    for arm, label in C_ARMS:
        out.append(f"| {label} | " + " | ".join(f"{fmt(cells.get((m, arm)), 'snapshot')} | {fmt(cells.get((m, arm)), 'suite')}" for m in models) + " |")
    out.append("")

out += ["## Paired, question by question (suite)", "",
        "A question counts as improved or regressed when its suite pass rate across repetitions moves by at least one half.", "",
        "| Model | From → to | Improved | Regressed | Mean change per question |", "| --- | --- | ---: | ---: | ---: |"]
for p in S["paired"]:
    out.append(f"| {NAMES[p['model']]} | {p['from']} → {p['to']} | {len(p['improved'])} | {len(p['regressed'])} | {p['mean_suite_rate_change']:+.2f} |")
out.append("")

out += ["## Frozen and corrected references compared (suite means)", "",
        "The corrected references change only suite scores. Most corrections add the function-or-method restriction the "
        "question states; directly prompted models usually omitted it as the frozen references did, so their suite "
        "scores fall, while Auto Ontology's agent with DeepSeek usually wrote it, so those scores rise.", "",
        "| Model | Arm | Frozen | Corrected |", "| --- | --- | ---: | ---: |"]
for (m, arm), c in cells.items():
    out.append(f"| {NAMES[m]} | {arm} | {mean(frozen.get((m, arm)), 'suite')} | {mean(c, 'suite')} |")
out.append("")

out += ["## Cost and time", "",
        "Auto Ontology's chat endpoint returns no provider usage, so arm C's cost and tokens were not captured.", "",
        "| Model | Arm | Median seconds per question | Total cost (USD) | Prompt tokens per request |", "| --- | --- | ---: | ---: | ---: |"]
for c in S["cells"]:
    cost = "Not captured" if c["cost_usd"] is None else f"{c['cost_usd']:.2f}"
    tok = "Not captured" if c["prompt_tokens_per_request"] is None else str(c["prompt_tokens_per_request"])
    out.append(f"| {NAMES[c['model']]} | {c['arm']} | {c['median_seconds']:.1f} | {cost} | {tok} |")
out.append("")
never = [q for q, n in power.items() if n == 0]
out += ["## Validity", "",
        "- Every reference reading runs on the real database and all eight counterfactual databases, and no corrected reference "
        "changes its answer on a real database (`python study/check_references.py`, [reference_check.json](results/reference_check.json)).",
        "- Rescoring with the frozen references reproduces the published frozen scores exactly; rescoring them on the regenerated "
        "counterfactual databases changes no score.",
        f"- The reference answer changes on at least one counterfactual database for {len(power) - len(never)} of {len(power)} questions; "
        f"for {', '.join(never)} the reference answer never changes, which limits the suite's ability to catch a fixed answer there.",
        "- 48 of 48 author–annotator agreements before rewording; 17 questions reworded, none removed ([adjudication](questions/adjudication.md)). "
        "The authors and annotators were AI models working under the protocol, not the repositories' maintainers.",
        "- Discarded runs: [results/discarded.md](results/discarded.md).", ""]
out += ["## Reproduce", "",
        "Rescoring needs no model calls. Build the databases (`sh study/build_data.sh`), then:", "",
        "```sh",
        "for r in auto_ontology click httpx rich; do python study/fuzz.py $r build/study/fuzz-corrected --variants 8 --seed 0; done",
        "python study/check_references.py",
        "python study/summarise.py --evaluator corrected",
        "python study/report.py",
        "```", "",
        "`python study/summarise.py --evaluator frozen --fuzz-dir build/study/fuzz-corrected --out <dir>` reproduces "
        "`results/frozen/` exactly. "
        "The scorer refuses to report a suite score unless all eight counterfactual databases are present, and records each "
        "database's SHA-256 in `scores.json`. Rerunning the models is described in [PROTOCOL.md](PROTOCOL.md).", ""]
(ROOT / "study/RESULTS.md").write_text("\n".join(out))
print("\n".join(out))
